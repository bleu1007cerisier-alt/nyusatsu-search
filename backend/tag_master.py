def flatten_master():
    """{タグ名: キーワードリスト} と {タグ名: カテゴリ} を返す。重複タグ名は起動時に検出。"""
    tag_keywords = {}
    tag_category = {}
    for cat, tags in TAG_MASTER.items():
        for tag, kws in tags.items():
            if tag in tag_keywords:
                raise ValueError(f"タグ名が重複しています: {tag}")
            tag_keywords[tag] = kws
            tag_category[tag] = cat
    return tag_keywords, tag_category
