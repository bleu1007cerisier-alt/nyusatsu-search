import re as _re_fb

# キーワード照合・継承のいずれでもタグが付かなかった案件に、
# 最低1つ「案件形態」タグを保証する最終フォールバック（タグ0件を無くすため）。
# 全ての調達は工事/物品/賃貸借/役務のいずれかであり、案件形態は実務者が使う有用なファセット。
_FB_WORKS = _re_fb.compile(r"工事|施工|舗装|改築|新築|増築|補修|外構|しゅんせつ|土木|建て替|建替")
_FB_RENT = _re_fb.compile(r"賃貸借|リース|借上|借入|レンタル|貸与")
_FB_SALE = _re_fb.compile(r"売払|売却|公売|売り払|処分(?!場)")
_FB_GOODS = _re_fb.compile(
    r"購入|調達|買入|買収|買受|供給|納入|物品|備品|用紙|洗剤|装置|機器|部品|"
    r"外\d*点|ほか\d*点|供与|外$|購入取付|購入据付")
_FB_SERVICE = _re_fb.compile(
    r"業務|作業|運営|補助|支援|制作|作成|調査|点検|保守|運用|管理|委託|派遣|"
    r"研修|事業|検討|企画|処理|相談|指導|プログラム|検査|手配|警備|清掃|"
    r"サービス|等業務|一式")


def fallback_case_tag(title: str, category: str = "") -> str:
    """タグ0件の案件に付与する案件形態タグを推定する（必ず1つ返す）。"""
    t = title or ""
    if _FB_WORKS.search(t):
        return "工事"
    if _FB_RENT.search(t):
        return "賃貸借・リース"
    if _FB_SALE.search(t):
        return "売払・公売"
    if _FB_GOODS.search(t):
        return "物品購入"
    if category == "プロポーザル" or _FB_SERVICE.search(t):
        return "業務委託"
    return "業務委託"  # 最終デフォルト（役務）


def flatten_master():
    """{タグ名: キーワードリスト} と {タグ名: カテゴリ} を返す。重複タグ名は起動時に検出。"""
    tag_keywords = {}
    tag_category = {}
    for cat, tags in TAG_MASTER.items():
        for tag, kws in tags.items():
            if tag in tag_keywords:
                raise ValueError(f"タグ名が重複しています: {tag}")
            tag_keywords[tag] = kws
            tag_category[tag] = cat
    return tag_keywords, tag_category
